import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { escapeHTML } from "./data.js";

const root = path.resolve(import.meta.dirname, "..");
const clientScripts = ["app.js", "views.js", "data.js", "icons.js", "map.js", "discovery.js", "methodology.js"];

export function siteOrigin(env = {}) {
  const value = env.SITE_URL || (env.VERCEL_PROJECT_PRODUCTION_URL ? `https://${env.VERCEL_PROJECT_PRODUCTION_URL}` : env.VERCEL_URL ? `https://${env.VERCEL_URL}` : "");
  if (!value) {
    if (env.VERCEL === "1") throw new Error("Enable Vercel system environment variables or set SITE_URL to the public HTTPS domain.");
    return "";
  }
  const url = new URL(value);
  if (!["http:", "https:"].includes(url.protocol) || url.username || url.password || url.pathname !== "/" || url.search || url.hash) throw new Error("SITE_URL must be an HTTP(S) origin without credentials, a path, query, or hash.");
  if (env.VERCEL === "1" && url.protocol !== "https:") throw new Error("Public Vercel sharing metadata requires an HTTPS SITE_URL.");
  return url.origin;
}

export function buildSite({ outputDirectory = path.join(root, "dist"), env = process.env } = {}) {
  const origin = siteOrigin(env);
  fs.mkdirSync(outputDirectory, { recursive: true });
  const marker = path.join(outputDirectory, ".racik-static-output");
  if (fs.readdirSync(outputDirectory).length && !fs.existsSync(marker)) throw new Error("Refusing to overwrite an unrecognized output directory. Choose a new, empty directory.");
  fs.writeFileSync(marker, "Generated by scripts/build.js; source files remain untouched.\n");
  for (const directory of ["assets", "styles", "data"]) fs.cpSync(path.join(root, directory), path.join(outputDirectory, directory), { recursive: true });
  fs.mkdirSync(path.join(outputDirectory, "scripts"), { recursive: true });
  for (const script of clientScripts) fs.copyFileSync(path.join(root, "scripts", script), path.join(outputDirectory, "scripts", script));
  let html = fs.readFileSync(path.join(root, "index.html"), "utf8");
  const metadata = [];
  if (origin) {
    const homepage = `${origin}/`;
    const image = `${origin}/assets/provinces/lake-toba.jpg`;
    metadata.push(`<link rel="canonical" href="${escapeHTML(homepage)}">`, `<meta property="og:url" content="${escapeHTML(homepage)}">`, `<meta property="og:image" content="${escapeHTML(image)}">`, '<meta property="og:image:type" content="image/jpeg">', '<meta property="og:image:alt" content="Danau Toba dan perbukitan Sumatera Utara · Dio Nando Hasibuan · CC0">', `<meta name="twitter:image" content="${escapeHTML(image)}">`, '<meta name="twitter:image:alt" content="Danau Toba dan perbukitan Sumatera Utara">');
  }
  if (env.VERCEL_ENV === "preview") metadata.push('<meta name="robots" content="noindex, nofollow">');
  html = html.replace("</head>", `${metadata.map((line) => `  ${line}`).join("\n")}\n</head>`);
  fs.writeFileSync(path.join(outputDirectory, "index.html"), html);
  return { outputDirectory, origin };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const result = buildSite();
  console.log(`Static site prepared in ${result.outputDirectory}`);
  console.log(result.origin ? `Main-site sharing URLs: ${result.origin}` : "Local build: set SITE_URL to include absolute sharing/canonical URLs.");
}
